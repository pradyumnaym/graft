class NoPeopleDetected(RuntimeError):
    """Raised by :meth:`GRAFTModel.predict` when the pose estimator finds nobody.

    Subclasses ``RuntimeError`` because the benchmark harness catches that to skip
    a frame; keep it that way.
    """


@dataclass
class GRAFTConfig:
    """Architecture of a GRAFT checkpoint.

    Only two fields differ between the two published checkpoints
    (``drop_vis_feats`` and ``flat_hand_mean``); the rest are fixed by the
    trained weights and should not be changed when loading one.
    """

    #: Side of the square feature-sampling window, in feature-map cells.
    sample_radius: int = 3
    #: Width of the refinement transformer.
    dim: int = 512
    #: Probability of hiding a context point during training. Inert at eval.
    feedback_dropout_prob: float = 0.3
    #: Probability of zeroing a query point's geometry during training. Inert at eval.
    geometry_dropout_prob: float = 0.0
    #: Add 64 extra surface tokens. Off in both published checkpoints.
    additional_tokens: bool = False
    #: How the NLF initialisation is brought onto the scene point map:
    #: ``'scale'`` (published) rescales the body about the camera;
    #: ``'transl'`` only shifts it.
    alignment_type: str = "scale"
    #: Blind the model to image features (the "without visual features" ablation).
    #: Sample points are pushed out of bounds, so the transformer sees geometry only.
    drop_vis_feats: bool = False
    #: SMPL-X hand-mean convention the checkpoint was trained under. This must
    #: match the checkpoint: it changes what a zero hand pose means.
    flat_hand_mean: bool = True
    #: Run the refinement transformer in bfloat16. Off for the published numbers.
    use_bf16: bool = False


@dataclass
class GRAFTOutput:
    """What :meth:`GRAFTModel.predict` returns for one image."""

    #: SMPL-X parameters in the scene frame, each ``(n_people, ...)``:
    #: ``betas, transl, global_orient, body_pose, left_hand_pose,
    #: right_hand_pose, jaw_pose, expression``.
    smplx: dict[str, torch.Tensor]
    #: Posed SMPL-X vertices, ``(n_people, 10475, 3)``, scene frame, metres.
    vertices: torch.Tensor
    #: SMPL-X joints, ``(n_people, 127, 3)``, scene frame, metres.
    joints: torch.Tensor
    #: Metric scene point map, ``(H, W, 3)``, camera frame, metres.
    points: torch.Tensor
    #: Camera intrinsics recovered from the point map, ``(3, 3)``, pixels.
    K: torch.Tensor
    #: The NLF initialisation the refinement started from, same layout as ``smplx``.
    init: dict[str, torch.Tensor]
    #: Number of people found.
    n_people: int

    def __len__(self) -> int:
        return self.n_people


class GRAFTModel(torch.nn.Module):
    """Human-scene reconstruction from a single image.

    A learned human-scene-interaction prior: it predicts iterative,
    geometry-grounded refinements of an off-the-shelf pose estimate.

    Construct with :meth:`from_pretrained` and call :meth:`predict`. The
    lower-level :meth:`infer` takes the batch dictionary directly and is what the
    evaluation harness uses.

    Frozen components (MapAnything, NLF, MoGe, WiLoR, SMPL-X) live in ``self._ext``
    rather than as submodules, so a checkpoint holds only GRAFT's own weights. They
    load lazily via the ``require_*`` methods.
    """

    def __init__(
        self,
        config: Optional[GRAFTConfig] = None,
        **overrides: Any,
    ):
        super().__init__()
        cfg = config if config is not None else GRAFTConfig()
        if overrides:
            cfg = GRAFTConfig(**{**vars(cfg), **overrides})
        self.config = cfg

        # Mirrored onto the instance because the verbatim forward code reads them
        # as plain attributes.
        self.sample_radius = cfg.sample_radius
        self.dim = cfg.dim
        self.feedback_dropout_prob = cfg.feedback_dropout_prob
        self.geometry_dropout_prob = cfg.geometry_dropout_prob
        self.additional_tokens = cfg.additional_tokens
        self.alignment_type = cfg.alignment_type
        self.drop_vis_feats = cfg.drop_vis_feats
        self.flat_hand_mean = cfg.flat_hand_mean
        self.use_bf16 = cfg.use_bf16

        self._ext: dict[str, Any] = {}
        self._ext['model_ma'] = MapAnything.from_pretrained("facebook/map-anything").eval()
        self._ext['model_nlf'] = None    # lazily loaded by require_nlf
        self._ext['model_moge'] = None   # lazily loaded by require_moge
        smplx_neutral = str(paths.require(paths.smplx_neutral(), "SMPL-X neutral body model"))
        self._ext['smplx_aa'] = smplx.SMPLX(
            smplx_neutral, num_betas=10, use_pca=False, flat_hand_mean=cfg.flat_hand_mean)
        self._ext['smplx_rotmat'] = smplx.SMPLXLayer(
            smplx_neutral, num_betas=10, use_pca=False)

        self.sampler = FusedFeatureSampler(
            output_dims=512, input_dims=[1536] * 4, num_views=2,
            sample_radius=cfg.sample_radius, use_embeddings=True)

        self.features_xyz = LearnableFourierFeatures(in_features=3, out_features=64, concat_input=True)
        self.features_vec = LearnableFourierFeatures(in_features=3, out_features=64, concat_input=True)
        self.features_norm = LearnableFourierFeatures(in_features=3, out_features=64, concat_input=True)

        self.mlp_body = MLP([207, 512, 512], activation=torch.nn.GELU)
        self.mlp_point = MLP([67 * 3, 16, 16], activation=torch.nn.GELU)
        self.mlp_hand = MLP([16 * 5 + 90, 512, 512], activation=torch.nn.GELU)
        self.mlp_full = MLP([451, 512, 512], activation=torch.nn.GELU)

        self.n_tokens = 24
        if cfg.additional_tokens:
            self.mlp_addnl = MLP([67 * 3, 512, 512], activation=torch.nn.GELU)
            self.n_tokens += 64

        self.embeddings = torch.nn.Parameter(torch.randn(1, self.n_tokens, 512))
        self.dec_body_pose = MLP([512, 256, 6], activation=torch.nn.GELU)
        self.dec_pos = MLP([512, 256, 3], activation=torch.nn.GELU)
        self.dec_global_orient = MLP([512, 256, 6], activation=torch.nn.GELU)
        self.dec_hand = MLP([512, 256, 90], activation=torch.nn.GELU)
        self.dec_betas = MLP([512, 256, 10], activation=torch.nn.GELU)
        self.dec_scale = MLP([512, 256, 1], activation=torch.nn.GELU)

        # ImageNet statistics: MapAnything's DINOv2 encoder expects them.
        self.register_buffer('mean', torch.tensor([0.485, 0.456, 0.406]).view(1, 3, 1, 1))
        self.register_buffer('std', torch.tensor([0.229, 0.224, 0.225]).view(1, 3, 1, 1))

        # depth=5 and heads=dim//64 are fixed by the trained weights.
        self.transformer = TransformerCrossAttn(
            dim=cfg.dim,
            depth=5,
            heads=cfg.dim // 64,
            dim_head=64,
            mlp_dim=cfg.dim,
            dropout=0.0,
            norm="layer",
            norm_cond_dim=-1,
            context_dim=cfg.dim,
        )

    def train(self, mode=True):
        res = super().train(mode)
        # set MA and NLF to eval mode - they are not trained
        if 'wilor' in self._ext:
            self._ext['wilor'].wilor_model.eval()
        for key in self._ext:
            if self._ext[key] is not None and key != 'wilor':
                self._ext[key].eval()

        return res

    def to(self, *args, **kwargs):
        # Call parent to() for regular parameters
        super().to(*args, **kwargs)
        # Manually move models in the dict
        if 'wilor' in self._ext and self._ext['wilor'] is not None:
            self._ext['wilor'].wilor_model.to(*args, **kwargs)

        for key in self._ext:
            if self._ext[key] is not None:
                self._ext[key] = self._ext[key].to(*args, **kwargs)
        return self

    def cuda(self):
        return self.to(device='cuda')

    def cpu(self):
        return self.to(device='cpu')

    def require_moge(self, device='cuda'):
        """Load MoGe, used to put MapAnything's point map in metric scale."""
        if self._ext['model_moge'] is None:
            from moge.model.v2 import MoGeModel
            self._ext['model_moge'] = MoGeModel.from_pretrained("Ruicheng/moge-2-vitl-normal").eval().to(device)

    def require_nlf(self, device='cuda'):
        """Load the NLF pose detector that provides GRAFT's initialisation."""
        if self._ext['model_nlf'] is None:
            ckpt = paths.require(paths.nlf_torchscript(), "NLF detector")
            self._ext['model_nlf'] = torch.jit.load(str(ckpt), map_location=device).eval()

    def require_wilor(self, device='cuda'):
        """Load WiLoR, used only when ``use_wilor_hands=True`` to refine hands."""
        if self._ext.get('wilor') is None:
            # Lazy import: pulling wilor_mini imports ultralytics, which sets
            # CUBLAS_WORKSPACE_CONFIG=:4096:8 (deterministic-slow cuBLAS). Only pay that on
            # demand, and re-pop it so the rest of the process stays fast.
            with optional("demo", "Hand refinement (refine_hands=True)"):
                from wilor_mini.pipelines.wilor_hand_pose3d_estimation_pipeline import WiLorHandPose3dEstimationPipeline
            enable_fast_gemm()
            self._ext['wilor'] = WiLorHandPose3dEstimationPipeline(device=device, dtype=torch.float16, verbose=False)
            self._ext['wilor'].wilor_model.to(device)

    def _get_hand_pose(self, images: torch.Tensor, keypoints_2d, image_idx=None):
        # images: (B,3,H,W). keypoints_2d: (N_h, J, 2|3) for the valid humans (batch['idxs'] order).
        # image_idx: (N_h,) source-image index per human (None => all image 0, i.e. B=1).
        # Batched: groups hands by source image and runs ONE wilor_model forward across all of them.
        with optional("demo", "Hand refinement (refine_hands=True)"):
            from .ops.wilor_batch import batched_predict_with_bboxes
        B = images.shape[0]
        images_np = [(images[b].cpu().permute(1, 2, 0).numpy() * 255.0).astype(np.uint8) for b in range(B)]
        keypoints_2d = keypoints_2d.cpu().numpy()
        n_humans = keypoints_2d.shape[0]
        if image_idx is None:
            image_idx = np.zeros(n_humans, dtype=np.int64)
        elif torch.is_tensor(image_idx):
            image_idx = image_idx.cpu().numpy()
        img_h, img_w = images_np[0].shape[:2]

        def _make_bbox(hand_joints_xy: np.ndarray):
            x_min, y_min = hand_joints_xy.min(axis=0)
            x_max, y_max = hand_joints_xy.max(axis=0)
            x1 = np.clip(x_min, 0, img_w - 1)
            y1 = np.clip(y_min, 0, img_h - 1)
            x2 = np.clip(x_max, 0, img_w - 1)
            y2 = np.clip(y_max, 0, img_h - 1)
            if (x2 - x1) < 2 or (y2 - y1) < 2:
                return None
            return np.array([x1, y1, x2, y2], dtype=np.float32)

        # Group hand bboxes by source image; track (human, is_right) per bbox to scatter back.
        bboxes_per_img = [[] for _ in range(B)]
        is_rights_per_img = [[] for _ in range(B)]
        owner_per_img = [[] for _ in range(B)]   # owner_per_img[b][k] = (human, is_right)
        for human in range(n_humans):
            b = int(image_idx[human])
            left_hand_joints = keypoints_2d[human, [JOINT_NAMES.index('left'+name) for name in all_hand_joint_names], :]
            right_hand_joints = keypoints_2d[human, [JOINT_NAMES.index('right'+name) for name in all_hand_joint_names], :]
            left_hand_bbox = _make_bbox(left_hand_joints)
            if left_hand_bbox is not None:
                bboxes_per_img[b].append(left_hand_bbox); is_rights_per_img[b].append(0); owner_per_img[b].append((human, 0))
            right_hand_bbox = _make_bbox(right_hand_joints)
            if right_hand_bbox is not None:
                bboxes_per_img[b].append(right_hand_bbox); is_rights_per_img[b].append(1); owner_per_img[b].append((human, 1))

        results = [{'left_hand': None, 'right_hand': None} for _ in range(n_humans)]
        if sum(len(b) for b in bboxes_per_img) == 0:
            return results

        bboxes_arr = [np.asarray(b, dtype=np.float32) if b else np.empty((0, 4), np.float32) for b in bboxes_per_img]
        outputs_per_img = batched_predict_with_bboxes(self._ext['wilor'], images_np, bboxes_arr, is_rights_per_img)

        for b in range(B):
            for k, out in enumerate(outputs_per_img[b]):
                person_id, is_right_from_vitpose = owner_per_img[b][k]
                if is_right_from_vitpose != out['is_right']:   # pipeline echoes input is_right; guard kept for parity
                    continue
                saving_output = {
                    'hand_bbox': np.array(out['hand_bbox'], dtype=np.float32),
                    'global_orient': out['wilor_preds']['global_orient'][0],
                    'hand_pose': out['wilor_preds']['hand_pose'][0],
                    'betas': out['wilor_preds']['betas'][0],
                    'pred_keypoints_3d': out['wilor_preds']['pred_keypoints_3d'][0],
                    'pred_keypoints_2d': out['wilor_preds']['pred_keypoints_2d'][0],
                }
                if is_right_from_vitpose:
                    results[person_id]['right_hand'] = saving_output
                else:
                    results[person_id]['left_hand'] = saving_output
        return results

    def _process_input(self, batch, noisy_align, use_moge, use_moge_scale=False, use_wilor_hands=False):
        device = batch['image'].device
        # Normalize input images for MapAnything
        scene_image = (batch['scene_image'] - self.mean) / self.std
        image = (batch['image'] - self.mean) / self.std

        ###################################################
        # Extract features using MapAnything
        ###################################################
        views = [
            {"img": scene_image, "true_shape": batch['scene_image'].shape[2:], "idx": 0, "instance": '0', "data_norm_type": ['dinov2'], 'camera_poses': torch.eye(4).unsqueeze(0).repeat(batch['scene_image'].shape[0], 1, 1).to(device)}, 
            {"img": image, "true_shape": batch['image'].shape[2:], "idx": 1, "instance": '1', "data_norm_type": ['dinov2'], 'camera_poses': torch.eye(4).unsqueeze(0).repeat(batch['image'].shape[0], 1, 1).to(device)}
        ]

        ###################################################
        # Scene geometry, and the per-frame pose initialisation
        ###################################################
        self.require_nlf(device=device)
        with torch.inference_mode():
            model_output, allfeats, _ = self._ext['model_ma'].infer(views, apply_mask=False, mask_edges=False)
                
        if use_moge_scale:
            self.require_moge(device=device)
            assert not use_moge, "Only one of use_moge and use_moge_scale can be True at the same time"
            # use MoGe only for scale, not geometry
            input_images = torch.cat([batch['scene_image']], dim=0)
            output = self._ext['model_moge'].infer(input_images)
            points = output['points']
            # align MA points to MoGe points
            model_output[0]['pts3d'], scale, z_shift =  align_points_robust_batched(
                model_output[0]['pts3d'],
                points,
                mask=torch.isfinite(model_output[0]['pts3d']).all(dim=-1) & torch.isfinite(points).all(dim=-1),
                return_transform=True
            )

            model_output[1]['pts3d'] = model_output[1]['pts3d'] * scale[:, None, None]
            model_output[1]['pts3d'][..., 2] += z_shift

            model_output[0]['intrinsics'] = pointmap_to_intrinsics_batch(model_output[0]['pts3d'])

        elif use_moge:
            self.require_moge(device=device)
            # Use MoGe to get depth maps
            input_images = torch.cat([batch['scene_image'], batch['image']], dim=0)
            output = self._ext['model_moge'].infer(input_images)
            # convert intrinsics to pixel units
            intrinsics = torch.tensor([[input_images.shape[3], 0, 0],
                                       [0, input_images.shape[2], 0],
                                       [0, 0, 1]], dtype=torch.float32).to(input_images.device) @ output['intrinsics']
            points = output['points'].chunk(2, dim=0)
            intrinsics = intrinsics.chunk(2, dim=0)
            model_output[0]['pts3d'] = points[0]
            model_output[0]['intrinsics'] = intrinsics[0]
            model_output[1]['pts3d'] = points[1]
            model_output[1]['intrinsics'] = intrinsics[1]

            if 'non_human_mask' in batch:
                model_output[1]['pts3d'] = align_points_robust_batched(
                    model_output[1]['pts3d'],
                    model_output[0]['pts3d'],
                    mask=batch['non_human_mask'] & torch.isfinite(model_output[1]['pts3d']).all(dim=-1) & \
                            torch.isfinite(model_output[0]['pts3d']).all(dim=-1)
                )
                
            # set non-finite points to 0 to prevent issues in later processing - they will be masked out anyway
            model_output[1]['pts3d'][~torch.isfinite(model_output[1]['pts3d']).all(dim=-1)] = 0.0
            model_output[0]['pts3d'][~torch.isfinite(model_output[0]['pts3d']).all(dim=-1)] = 0.0
                
        # No GT: inference time -- fast NLF (detect_poses + batched compiled fit)
        smplx_params_nlf = detect_parametric_fast(
            self, batch['image'], model_output[0]['intrinsics'])
        valid_humans = torch.zeros(batch['image'].shape[0], max(x['boxes'].shape[0] for x in smplx_params_nlf), dtype=torch.bool, device=device)
        for i in range(batch['image'].shape[0]):
            valid_humans[i, :smplx_params_nlf[i]['boxes'].shape[0]] = 1

        batch['valid_humans'] = valid_humans
        batch['idxs'] = torch.where(batch['valid_humans'])
        batch['pts3d_scene'] = recursive_detach(model_output[0]['pts3d'])
        batch['depth_points_gt'] = torch.zeros(
            *batch['valid_humans'].shape,
            *batch['image'].shape[2:],
            3,
            device=device
        )
        batch['depth_points_gt'][batch['valid_humans']] = recursive_detach(model_output[1]['pts3d'][batch['idxs'][0]])
        batch['pts3d_human'] = batch['depth_points_gt']
        batch['K_scene'] = recursive_detach(model_output[0]['intrinsics'])

        B, N_h = batch['valid_humans'].shape
        smplx_data_nlf = {
            'betas': torch.zeros(B, N_h, 10, device=device),
            'transl': torch.zeros(B, N_h, 3, device=device),
            'global_orient': torch.zeros(B, N_h, 3, device=device),
            'body_pose': torch.zeros(B, N_h, 21, 3, device=device),
            'left_hand_pose': torch.zeros(B, N_h, 15, 3, device=device),
            'right_hand_pose': torch.zeros(B, N_h, 15, 3, device=device),
            'expression': torch.zeros(B, N_h, 10, device=device),
            'jaw_pose': torch.zeros(B, N_h, 3, device=device),
        }
            
        for i in range(len(smplx_params_nlf)):
            for key in ['betas', 'transl', 'global_orient', 'body_pose', 'left_hand_pose', 'right_hand_pose']:
                # Scatter by MASK, not into the first-n slots: every consumer reads these
                # back with [batch['valid_humans']], so a prefix write is only correct when
                # the valid mask happens to be contiguous. An unwritten row would be an
                # all-zero human -- a T-pose at the camera origin -- which then also
                # poisons human_origins and hence the query tokens of both branches.
                smplx_data_nlf[key][i][batch['valid_humans'][i]] = smplx_params_nlf[i][key]
        # Sanitise non-finite NLF initialisations (a fraction of a percent overall,
        # more in dense crowds): replace NaN/Inf with 0 so the forward stays finite.
        # Every person is kept -- dropping one here would desynchronise the person
        # count that valid_humans / idxs index with.
        for key in ('betas', 'transl', 'global_orient', 'body_pose', 'left_hand_pose', 'right_hand_pose'):
            smplx_data_nlf[key] = torch.nan_to_num(smplx_data_nlf[key], nan=0.0, posinf=0.0, neginf=0.0)
        batch['smplx_data_nlf'] = smplx_data_nlf



        enc_feats, final_feats, interm_feats = recursive_detach(allfeats)
        # Backbone features + the human index come from inference_mode regions (frozen backbone /
        # prepare_gt) and keep the inference flag through .detach(). In TRAINING they feed the
        # learnable projection and index grad-requiring tensors in the backward pass, where
        # inference tensors cannot be saved -- materialize them to normal tensors when grad is on.
        # No-op during inference, so the fast inference path is untouched. (Fixes regression from 8c1600c.)
        batch['input_features'] = recursive_materialize([enc_feats, interm_feats[0].features, interm_feats[1].features, final_feats.features])
        batch['idxs'] = recursive_materialize(batch['idxs'])

        ###################################################
        # Align NLF outputs to the depth maps
        ###################################################
        nlf_out = self._ext['smplx_aa'](
            global_orient=batch['smplx_data_nlf']['global_orient'][batch['valid_humans']],
            body_pose=batch['smplx_data_nlf']['body_pose'][batch['valid_humans']],
            jaw_pose=batch['smplx_data_nlf']['jaw_pose'][batch['valid_humans']],
            leye_pose = self._ext['smplx_aa'].leye_pose.reshape(1,3).repeat(batch['valid_humans'].sum(),1).to(device),
            reye_pose = self._ext['smplx_aa'].reye_pose.reshape(1,3).repeat(batch['valid_humans'].sum(),1).to(device),
            left_hand_pose=batch['smplx_data_nlf']['left_hand_pose'][batch['valid_humans']],
            right_hand_pose=batch['smplx_data_nlf']['right_hand_pose'][batch['valid_humans']],
            betas=batch['smplx_data_nlf']['betas'][batch['valid_humans']],
            transl=batch['smplx_data_nlf']['transl'][batch['valid_humans']].reshape(-1,3).to(device),
            expression=torch.zeros(batch['valid_humans'].sum(), 10).to(device)
        )

        nlf_joints_2d = torch.round(project_points_torch_batch(
            nlf_out.joints.detach(),
            K= batch['K_scene'][batch['idxs'][0]].to(device).float()
        )).long()   # N_h x 127 x 2

        nlf_head_joints = nlf_joints_2d[:, 15]      # N_h x 2
        N_h = nlf_head_joints.shape[0]
        ys = nlf_head_joints[:, 1].clamp(0, batch['image'].shape[2] - 1)
        xs = nlf_head_joints[:, 0].clamp(0, batch['image'].shape[3] - 1)
        batch_idx = torch.arange(N_h, device=ys.device)

        gt_points = batch['pts3d_human'][batch['valid_humans']][batch_idx, ys, xs]  # (N_h, 3)
        # head-surface anchor via ray-triangle (replaces the full-mesh depth render):
        # camera origin -> SMPL-X head joint, frontmost hit on the head+neck faces.
        nlf_points = head_anchor_points(self, nlf_out.vertices, nlf_out.joints[:, 15])  # (N_h, 3)

        batch['smplx_data_nlf_aligned'] = {k: v.clone() for k, v in batch['smplx_data_nlf'].items()}

        if self.alignment_type == 'transl':
            translations = gt_points - nlf_points

            if noisy_align:
                translations[:, :2] += torch.randn_like(translations[:, :2]) * 0.03
                translations[:, 2] += torch.randn_like(translations[:, 2]) * 0.06

            # apply the translations to the NLF model outputs
            batch['smplx_data_nlf_aligned']['transl'][batch['valid_humans']] += translations
            nlf_aligned_joints = nlf_out.joints + translations[:, None, :]

        elif self.alignment_type == 'scale':
            # Apply scaling
            scales = gt_points[:, 2] / (nlf_points[:, 2] + 1e-8)
            scales[abs(scales) > 3.0] = 1.0   # prevent extreme scales
            if noisy_align:
                scales += torch.randn_like(scales) * 0.03

            smplx_data_nlf_aligned = scale_smplx_params(
                {k: v[batch['valid_humans']] for k, v in batch['smplx_data_nlf'].items()},
                scales[:, None]
            )
            for key in batch['smplx_data_nlf_aligned']:
                batch['smplx_data_nlf_aligned'][key][batch['valid_humans']] = smplx_data_nlf_aligned[key]
            nlf_aligned_joints = nlf_out.joints * scales[:, None, None]
        else:
            raise ValueError(f"Invalid alignment type: {self.alignment_type}")

        batch['human_origins'] = nlf_aligned_joints[:, 0, :]        # N_h x 3 - the aligned pelvis joints are used as human origins - for all 3D coordinates.
        batch['pts3d_normals'] = compute_point_normals(batch['pts3d_scene'].to(device))

        if use_wilor_hands:
            self.require_wilor(device=device)
            hand_poses = self._get_hand_pose(batch['image'], nlf_joints_2d, batch['idxs'][0])
            for i, result in enumerate(hand_poses):
                b_idx = batch['idxs'][0][i]
                h_idx = batch['idxs'][1][i]
                if result['left_hand'] is not None:
                    batch['smplx_data_nlf_aligned']['left_hand_pose'][b_idx, h_idx] = torch.from_numpy(result['left_hand']['hand_pose']).to(device)
                if result['right_hand'] is not None:
                    batch['smplx_data_nlf_aligned']['right_hand_pose'][b_idx, h_idx] = torch.from_numpy(result['right_hand']['hand_pose']).to(device)

    def _update_parameters(self, pts3d, normals, features, smplx_data, origins, K, image, need_fitted_params=True, features_are_projected=False, compute_verts=True):
        n_humans = smplx_data['betas'].shape[0]

        ######################################################################
        # SMPLX forward pass
        ######################################################################

        out_smplx = self._ext['smplx_aa'](
            global_orient=smplx_data['global_orient'],
            body_pose=smplx_data['body_pose'],
            jaw_pose=smplx_data['jaw_pose'],
            leye_pose = self._ext['smplx_aa'].leye_pose.reshape(1,3).repeat(n_humans,1).to(pts3d.device),
            reye_pose = self._ext['smplx_aa'].reye_pose.reshape(1,3).repeat(n_humans,1).to(pts3d.device),
            left_hand_pose=smplx_data['left_hand_pose'],
            right_hand_pose=smplx_data['right_hand_pose'],
            betas=smplx_data['betas'],
            transl=smplx_data['transl'].reshape(-1,3).to(pts3d.device),
            expression=torch.zeros(n_humans, 10).to(pts3d.device)
        )   # N_h humans

        smplx_data_6d = convert_smplx_params_to_6d(smplx_data)

        # prepare the query tokens
        body_joints = out_smplx.joints[:, 1:22, :]                                                                      # N_h x 21 x 3
        left_hand_joints = out_smplx.joints[:, [JOINT_NAMES.index('left'+name) for name in hand_joint_names], :]        # N_h x 5 x 3
        right_hand_joints = out_smplx.joints[:, [JOINT_NAMES.index('right'+name) for name in hand_joint_names], :]      # N_h x 5 x 3
        surface_points = out_smplx.vertices[:, sampled_point_indices, :]                                                # N_h x 27 x 3
        surface_points_addnl = out_smplx.vertices[:, sampled_point_indices_64, :] if self.additional_tokens else None                     # N_h x 64 x 3

        left_hand_joints_mean = left_hand_joints.mean(dim=1, keepdim=True)
        right_hand_joints_mean = right_hand_joints.mean(dim=1, keepdim=True)

        ######################################################################
        # Sample features from the image feature maps - for context tokens
        ######################################################################
        context_points = torch.cat([body_joints, left_hand_joints_mean, right_hand_joints_mean, surface_points], dim=1)  # N_h x (21+1+1+27) x 3
        if self.additional_tokens:
            context_points = torch.cat([context_points, surface_points_addnl], dim=1)   # N_h x (21+1+1+27+64) x 3
        context_points_2d = project_points_torch_batch(
            context_points,
            K= K,
        )   # N_h x N_q x 2
        context_points_2d = torch.stack([
            context_points_2d[:, :, 0] / (image.shape[3] - 1),
            context_points_2d[:, :, 1] / (image.shape[2] - 1)
        ], dim=-1)   # normalize to [0, 1] for grid_sample              # N_h x N_q x 2

        # randomly drop some context points for regularization
        if self.training and self.feedback_dropout_prob > 0.0:
            # just randomly set the points to out of bounds - it will be masked out in the sampler
            drop_mask = (torch.rand(n_humans, context_points_2d.shape[1], device=context_points_2d.device) < self.feedback_dropout_prob)
            context_points_2d[drop_mask] = -5.0   # out of bounds

        if self.drop_vis_feats:
            # set all points to out of bounds, drops all visual input.
            context_points_2d[:] = -5.0
        # State-memory pivot (2026-09-01): PER-ROW evidence deletion. `_deleted_rows` is a
        # (n_humans,) bool set by the caller for humans whose visual evidence is absent
        # (ghost rows / harness deletion); their context points go out-of-bounds so the
        # sampler marks every sample INVALID and attention excludes them -- the same path
        # as drop_vis_feats, restricted to rows. Absent/None => bit-identical.
        _del = getattr(self, '_deleted_rows', None)
        if _del is not None:
            _del = _del.to(context_points_2d.device)
            _R = context_points_2d.shape[0]
            if _del.shape[0] != _R:
                # training stacks the nlf + GT-query branches BRANCH-MAJOR (rows = K*N);
                # the per-human flag is tiled so both branches drop the same rows.
                if _R % _del.shape[0] != 0:
                    raise RuntimeError(f"_deleted_rows {tuple(_del.shape)} vs rows {_R}: not a branch multiple")
                _del = _del.repeat(_R // _del.shape[0])
            context_points_2d[_del] = -5.0

        context, mask = self.sampler(features, context_points_2d, features_are_projected=features_are_projected)

        final_context = torch.zeros(n_humans, self.n_tokens, 54, 512, device=context.device)
        final_mask = torch.zeros(n_humans, self.n_tokens, 54, device=context.device).bool()

        # Pack the two token families into one fixed (n_tokens, 54, 512) context block.
        # Joint and surface tokens attend to their whole sampled window across both
        # views (2 * radius^2 = 18 features); the single whole-body token instead takes
        # only the window CENTRE of each of the 27 surface points, which is also 54.
        # Same width, different meaning -- hence the two separate writes below.
        radius = self.sampler.sample_radius
        center_idx = radius**2 // 2

        features_2 = context[:, 23:50, [center_idx, radius**2 + center_idx], :]
        mask_2 = mask[:, 23:50, [center_idx, radius**2 + center_idx]]
        features_2 = features_2.reshape(n_humans, 1, -1, 512)                           # N_h x 1 x 54 x 512
        mask_2 = mask_2.reshape(n_humans, 1, -1)                                        # N_h x 1 x 54

        # set the body tokens' context: they just use all the radius^2 features
        final_context[:, :23, :radius**2 * 2, :] = context[:, :23, :, :]
        final_mask[:, :23, :radius**2 * 2] = mask[:, :23, :]

        # the body token only uses the center feature
        final_context[:, 23:24, :, :] = features_2
        final_mask[:, 23:24, :] = mask_2

        if self.additional_tokens:
            final_context[:, 24:, :radius**2 * 2, :] = context[:, 50:, :, :]
            final_mask[:, 24:, :radius**2 * 2] = mask[:, 50:, :]


        ######################################################################
        # Get geometric features for the query tokens
        ######################################################################

        all_query_points = torch.cat([body_joints, left_hand_joints, right_hand_joints, surface_points], dim=1)          # N_h x (21+5+5+27) x 3
        if self.additional_tokens:
            all_query_points = torch.cat([all_query_points, surface_points_addnl], dim=1)   # N_h x (21+5+5+27+64) x 3

        nearest_points, nearest_normals = get_nearest_points_and_normals(pts3d, all_query_points, normals)
        nearest_scene_vector = nearest_points - all_query_points                                                         # N_h x N_q x 3
        points_norm = all_query_points - origins[:, None, :]                                                             # N_h x N_q x 3

        # do geometric dropout for regularization
        if self.training and self.geometry_dropout_prob > 0.0:
            drop_mask = (torch.rand(n_humans, all_query_points.shape[1], device=all_query_points.device) < self.geometry_dropout_prob)
            nearest_scene_vector[drop_mask] = 0.0
            points_norm[drop_mask] = 0.0
            nearest_normals[drop_mask] = 0.0

        points_norm_f = self.features_xyz(points_norm)                                                                        # N_h x N_q x C
        nearest_scene_vector_f = self.features_vec(nearest_scene_vector)                                                      # N_h x N_q x C
        nearest_normals_f = self.features_norm(nearest_normals)                                                               # N_h x N_q x C

        ######################################################################
        # Prepare input tokens for the transformer
        ######################################################################
        input_tokens_body = torch.cat([
            points_norm_f[:, :21, :],
            nearest_scene_vector_f[:, :21, :],
            nearest_normals_f[:, :21, :],
            smplx_data_6d['body_pose']
        ], dim=-1)   # N_h x 21 x (C*3) + 6
        input_tokens_body = self.mlp_body(input_tokens_body)    # N_h x 21 x 512

        input_token_left_hand = torch.cat([
            self.mlp_point(torch.cat([
                points_norm_f[:, 21:26, :],
                nearest_scene_vector_f[:, 21:26, :],
                nearest_normals_f[:, 21:26, :]
            ], dim=-1)).reshape(n_humans, -1),
            smplx_data_6d['left_hand_pose'].reshape(n_humans, -1)
        ], dim=-1)   # N_h x 5 * (C*3) + 6 * 15
        input_token_left_hand = self.mlp_hand(input_token_left_hand).unsqueeze(1)    # N_h x 1 x 512

        input_token_right_hand = torch.cat([
            self.mlp_point(torch.cat([
                points_norm_f[:, 26:31, :],
                nearest_scene_vector_f[:, 26:31, :],
                nearest_normals_f[:, 26:31, :]
            ], dim=-1)).reshape(n_humans, -1),
            smplx_data_6d['right_hand_pose'].reshape(n_humans, -1)
        ], dim=-1)   # N_h x 5 * (C*3) + 6 * 15
        input_token_right_hand = self.mlp_hand(input_token_right_hand).unsqueeze(1)    # N_h x 1 x 512

        input_token_full = torch.cat([
            self.mlp_point(torch.cat([
                points_norm_f[:, 31:58, :],
                nearest_scene_vector_f[:, 31:58, :],
                nearest_normals_f[:, 31:58, :]
            ], dim=-1)).reshape(n_humans, -1),
            smplx_data_6d['global_orient'].reshape(n_humans, -1),
            smplx_data_6d['betas'].reshape(n_humans, -1),
            smplx_data_6d['transl'] - origins
        ], dim=-1)   # N_h x (27 * (C*3) + 6 + 10 + 3
        input_token_full = self.mlp_full(input_token_full).unsqueeze(1)    # _Nh x 1 x 512

        input_sequences = torch.cat([
            input_tokens_body,
            input_token_left_hand,
            input_token_right_hand,
            input_token_full
        ], dim=1)   # N_h x (21 + 1 + 1 + 1) x 512

        if self.additional_tokens:
            addnl_tokens = torch.cat([
                points_norm_f[:, 58:122, :],
                nearest_scene_vector_f[:, 58:122, :],
                nearest_normals_f[:, 58:122, :],
            ], dim=-1)   # N_h x 64 x (C*3)
            addnl_tokens = self.mlp_addnl(addnl_tokens)    # N_h x 64 x 512
            input_sequences = torch.cat([input_sequences, addnl_tokens], dim=1)    # N_h x (24 + 64) x 512

        input_sequences = input_sequences + self.embeddings

        # print("Input tokens body shape:", input_tokens_body.shape)
        # print("Input token left hand shape:", input_token_left_hand.shape)
        # print("Input token right hand shape:", input_token_right_hand.shape)
        # print("Input token full shape:", input_token_full.shape)
        # print("Input sequences shape:", input_sequences.shape)

        #######################################################################
        # Forward pass through the transformer
        #######################################################################

        with torch.autocast(device_type='cuda', dtype=torch.bfloat16, enabled=self.use_bf16):
            outputs = self.transformer(
                input_sequences,
                context=final_context.reshape(n_humans * self.n_tokens, 54, 512),
                context_mask=final_mask.reshape(n_humans * self.n_tokens, 54)
            )   # N_h x N_q x 512

        if self.use_bf16:
            outputs = outputs.float()

        pred_pose_delta = self.dec_body_pose(outputs[:, :21, :])          # N_h x 21 x 6
        pred_left_hand_delta = self.dec_hand(outputs[:, 21:22, :])        # N_h x 1 x 90
        pred_right_hand_delta = self.dec_hand(outputs[:, 22:23, :])       # N_h x 1 x 90
        pred_transl_delta = self.dec_pos(outputs[:, 23:24, :])               # N_h x 1 x 3
        pred_global_orient_delta = self.dec_global_orient(outputs[:, 23:24, :])  # N_h x 1 x 6
        pred_betas_delta = self.dec_betas(outputs[:, 23:24, :])            # N_h x 1 x 10
        pred_scales = self.dec_scale(outputs[:, 23:24, :])                      # N_h x 1 x 1

        # Update SMPLX parameters
        smplx_data_6d['body_pose'] = smplx_data_6d['body_pose'] + pred_pose_delta
        smplx_data_6d['left_hand_pose'] = smplx_data_6d['left_hand_pose'] + pred_left_hand_delta.reshape(n_humans, 15, 6)
        smplx_data_6d['right_hand_pose'] = smplx_data_6d['right_hand_pose'] + pred_right_hand_delta.reshape(n_humans, 15, 6)
        smplx_data_6d['transl'] = smplx_data_6d['transl'] + pred_transl_delta.reshape(n_humans, 3)
        smplx_data_6d['global_orient'] = smplx_data_6d['global_orient'] + pred_global_orient_delta.reshape(n_humans, 6)
        smplx_data_6d['betas'] = smplx_data_6d['betas'] + pred_betas_delta.reshape(n_humans, 10)

        # The scaled vertices/joints feed only the training loss; skip this SMPL-X forward
        # when the caller doesn't need them (inference reads only the returned params).
        # Verified bit-identical to computing-then-discarding.
        if compute_verts:
            smplx_data_new_rotmat = convert_smplx_params_6d_to_rotmat(smplx_data_6d)
            out_smplx_new = self._ext['smplx_rotmat'](
                global_orient=smplx_data_new_rotmat['global_orient'],
                body_pose=smplx_data_new_rotmat['body_pose'],
                jaw_pose=smplx_data_new_rotmat['jaw_pose'],
                left_hand_pose=smplx_data_new_rotmat['left_hand_pose'],
                right_hand_pose=smplx_data_new_rotmat['right_hand_pose'],
                betas=smplx_data_new_rotmat['betas'],
                transl=smplx_data_new_rotmat['transl'].reshape(-1,3).to(pts3d.device),
            )   # N_h humans
            scaled_vertices = out_smplx_new.vertices * pred_scales.reshape(n_humans, 1, 1)
            scaled_joints = out_smplx_new.joints * pred_scales.reshape(n_humans, 1, 1)
        else:
            scaled_vertices = scaled_joints = None
        
        # Refitted params from scaled vertices/joints (for next iteration, will be detached)
        # Skip fitting on last iteration since scaled_smplx_6d won't be used
        if need_fitted_params:
            # scaled_smplx_6d = convert_smplx_params_aa_to_6d(self.fit_smplx_to_vertices_joints(scaled_vertices, scaled_joints[:, :55, :]))
            scaled_smplx_6d = scale_smplx_params(
                smplx_data_6d,
                pred_scales.squeeze(-1) # N_h, 1, 1 -> N_h, 1
            )
        else:
            scaled_smplx_6d = None

        # Return: 
        # - smplx_data_6d: unscaled rotation params (for rotation loss)
        # - scaled_vertices, scaled_joints: for vertex/joint loss (accounts for predicted scale)
        # - scaled_smplx_6d: refitted params for next iteration (detached via recursive_detach), or None if last iter
        return smplx_data_6d, scaled_vertices, scaled_joints, scaled_smplx_6d

    def _refine_once(self, batch, smplx_data, need_fitted_params=True):
        device = batch['image'].device
        smplx_data_input = {k: v.clone() for k, v in smplx_data.items()}
        if len(smplx_data_input['transl'].shape) == 3:
            # we have the B, N_h, ... shape - select only the valid humans
            smplx_data_input = {k: v[batch['valid_humans']] for k, v in smplx_data_input.items()}
        else:
            # already N_h, ... shape
            pass

        # Cache the per-level feature projection ONCE: it does not change across refinement
        # iterations. Bit-identical to projecting every iteration, since the projection is a
        # Linear and commutes with the gather.
        if '_projected_features' not in batch:
            batch['_projected_features'] = self.sampler.precompute_projection(batch['input_features'])

        return self._update_parameters(
            batch['pts3d_scene'][batch['idxs'][0]].to(device),                            # (N_h, H, W, 3)
            batch['pts3d_normals'][batch['idxs'][0]].to(device),                    # (N_h, H, W, 3)
            ([[pm[0][batch['idxs'][0]].to(device), pm[1][batch['idxs'][0]].to(device)] for pm in batch['_projected_features']]
             if '_projected_features' in batch else
             [[x[0][batch['idxs'][0]].to(device), x[1][batch['idxs'][0]].to(device)] for x in batch['input_features']]),  # per-view maps (projected if cached)
            smplx_data_input,              # dict of smplx params for N_h humans
            batch['human_origins'].to(device),                                       # (N_h, 3)
            batch['K_scene'][batch['idxs'][0]].to(device).float(),
            batch['image'][batch['idxs'][0]].to(device),
            need_fitted_params=need_fitted_params,
            features_are_projected=('_projected_features' in batch),
            compute_verts=self.training,   # scaled verts feed only the training loss; skip at base eval
        )

    def forward(self, batch, num_iters=1, noisy_align=True, use_moge=True, use_moge_scale=False, skip_last_fit=True, current_smplx_params=None, use_wilor_hands=False):
        """Run the refinement loop over a prepared batch.

        `batch` needs `image` and `scene_image`, each (B, 3, H, W) float in [0, 1];
        everything else is filled in by `_process_input`. Each iteration re-samples
        scene geometry and image features at the current body's joints and surface
        points, and predicts a residual on top.

        Returns the raw per-iteration dict. Most callers want `predict` (images in,
        meshes out) or `infer` (batch in, parameters out in a stable layout)."""

        if current_smplx_params is None:
            self._process_input(batch, noisy_align=noisy_align, use_moge=use_moge, use_moge_scale=use_moge_scale, use_wilor_hands=use_wilor_hands)
        else:
            # Reuse batch metadata from a previous infer() call and only override
            # current human initialization.
            batch['smplx_data_nlf_aligned'] = {k: v.clone() for k, v in current_smplx_params.items()}

        output_dicts = {}

        # Iteration 1: skip fitting on last iter during training (skip_last_fit=True), always fit during inference
        (output_dicts['nlf_pred_1'], output_dicts['nlf_verts_1'], output_dicts['nlf_joints_1'],
         output_dicts['nlf_pred_1_scaled']) = self._refine_once(batch, batch['smplx_data_nlf_aligned'], need_fitted_params=(num_iters > 1 or not skip_last_fit))
        
        if 'smplx_data_query' in batch:
            (output_dicts['smplx_query_1'], output_dicts['smplx_query_verts_1'], output_dicts['smplx_query_joints_1'],
             output_dicts['smplx_query_1_scaled']) = self._refine_once(batch, batch['smplx_data_query'], need_fitted_params=(num_iters > 1 or not skip_last_fit))
        
        if num_iters >= 2:
            for iter_idx in range(2, num_iters + 1):
                # Use scaled (detached) params from previous iteration for input
                key_nlf = f'nlf_pred_{iter_idx}'
                (output_dicts[key_nlf], output_dicts[f'nlf_verts_{iter_idx}'], output_dicts[f'nlf_joints_{iter_idx}'],
                 output_dicts[f'nlf_pred_{iter_idx}_scaled']) = self._refine_once(
                    batch, 
                    recursive_detach(convert_smplx_params_6d_to_aa(
                        output_dicts[f'nlf_pred_{iter_idx - 1}_scaled']
                    )),
                    need_fitted_params=(iter_idx < num_iters or not skip_last_fit)
                )
                if 'smplx_data_query' in batch:
                    key_query = f'smplx_query_{iter_idx}'
                    (output_dicts[key_query], output_dicts[f'smplx_query_verts_{iter_idx}'], output_dicts[f'smplx_query_joints_{iter_idx}'],
                     output_dicts[f'smplx_query_{iter_idx}_scaled']) = self._refine_once(
                        batch, 
                        recursive_detach(convert_smplx_params_6d_to_aa(
                            output_dicts[f'smplx_query_{iter_idx - 1}_scaled']
                        )),
                        need_fitted_params=(iter_idx < num_iters or not skip_last_fit)
                    )

        return output_dicts

    def infer(self, batch, num_iters=3, noisy_align=False, use_moge=True, use_moge_scale=False, current_smplx_params=None, use_wilor_hands=False):
        """Run inference on a prepared batch and return SMPL-X parameters.

        The batch-dictionary entry point, used by the benchmark harness. `predict`
        wraps this with image loading and mesh posing.

        Returns a dict with `smplx_data` (each value (B, N_people, ...), valid
        entries selected by `valid_humans`), the NLF initialisation it started
        from, the scene point map `pts3d`, the intrinsics `K`, and the parameters
        after each intermediate iteration."""
        # Canary: re-pop the deterministic-cuBLAS env var if any import re-planted it, and
        # warn loudly if so (it silently ~2x's every GEMM — the post-paper 400->540 ms
        # regression). Self-healing + visible; see utils/perf.py for the full saga.
        enable_fast_gemm(warn_if_replanted=True)
        with torch.inference_mode():
            # skip_last_fit=False to get fitted scaled params on last iteration
            out = self.forward(
                batch,
                num_iters=num_iters,
                noisy_align=noisy_align,
                use_moge=use_moge,
                use_moge_scale=use_moge_scale,
                skip_last_fit=False,
                current_smplx_params=current_smplx_params,
                use_wilor_hands=use_wilor_hands
            )

        # Use scaled params for inference output (nlf_pred_X_scaled contains the fitted params after scaling)
        # reshape back to B, N_h, ... format
        valid_humans = batch['valid_humans']
        B = valid_humans.shape[0]
        N_h_max = valid_humans.shape[1]

        out_dict = {
            'pts3d': batch['pts3d_scene'],
            'K': batch['K_scene'],
            'valid_humans': valid_humans
        }

        smpl_out = {
            'betas': torch.zeros(B, N_h_max, 10, device=valid_humans.device),
            'transl': torch.zeros(B, N_h_max, 3, device=valid_humans.device),
            'global_orient': torch.zeros(B, N_h_max, 3, device=valid_humans.device),
            'body_pose': torch.zeros(B, N_h_max, 21, 3, device=valid_humans.device),
            'left_hand_pose': torch.zeros(B, N_h_max, 15, 3, device=valid_humans.device),
            'right_hand_pose': torch.zeros(B, N_h_max, 15, 3, device=valid_humans.device),
            'expression': torch.zeros(B, N_h_max, 10, device=valid_humans.device),
            'jaw_pose': torch.zeros(B, N_h_max, 3, device=valid_humans.device),
        }
        # Use scaled params for final output
        out_params = convert_smplx_params_6d_to_aa(out['nlf_pred_{}_scaled'.format(num_iters)])
        for key in smpl_out:
            smpl_out[key][valid_humans] = out_params[key]

        out_dict['smplx_data'] = smpl_out
        out_dict['smplx_data_nlf_aligned'] = batch['smplx_data_nlf_aligned']

        # Intermediate iterations also use scaled params
        for i in range(1, num_iters):
            smplx_out_iter = {k: v.clone() for k, v in smpl_out.items()}
            smplx_params_iter = convert_smplx_params_6d_to_aa(out['nlf_pred_{}_scaled'.format(i)])
            for k in smplx_out_iter:
                smplx_out_iter[k][valid_humans] = smplx_params_iter[k]
            out_dict['nlf_pred_{}'.format(i)] = smplx_out_iter

        return out_dict

